# Speaks every phrase of data/voice.json with a Windows voice (SAPI, System.Speech), on this
# machine, and writes one WAV per phrase plus the time of every word as the voice engine reports it.
# Nothing is installed and nothing leaves the machine. Windows only (Windows PowerShell 5.1).
#
#   powershell -ExecutionPolicy Bypass -File scripts/voice-sapi.ps1 [-Voice "Microsoft Zira Desktop"] [-Rate 0]
#   bun run voice:sapi
#
# Reads   data/voice.json          the phrases, written by the lead (id, text, at)
# Writes  audio/voice/<id>.wav     one file per phrase, 16-bit mono PCM
#         data/voice-words.json    per phrase: file, duration, words with start and end in seconds of that file
#
# Word start times come from the engine's SpeakProgress events (AudioPosition). SAPI gives no word
# end, so a word ends where the next begins; bun run score pulls each end back to where the sound
# of the word stops (src/sound/voice.ts). The files are written at 16 kHz: with the desktop voices
# tried, AudioPosition counts as if the output were 16 kHz, so at 24 kHz every time came out 1.5
# times too late. The caption marks | and / of the text are not spoken.
# The installed voices are listed with -List. System.Speech sees only the desktop voices; on a
# stock English Windows these are English only.
param(
  [string]$Voice = '',
  [int]$Rate = 0,
  [switch]$List
)
$SampleRate = 16000
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Speech
$app = Split-Path -Parent $PSScriptRoot
$synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
if ($List) {
  $synth.GetInstalledVoices() | ForEach-Object { '{0}  ({1})' -f $_.VoiceInfo.Name, $_.VoiceInfo.Culture }
  exit 0
}
$script = Get-Content -Raw -Encoding UTF8 (Join-Path $app 'data/voice.json') | ConvertFrom-Json
if ($Voice -eq '' -and $script.voice -and $script.voice.name) { $Voice = $script.voice.name }
if ($Voice -ne '') { $synth.SelectVoice($Voice) }
if ($script.voice -and $null -ne $script.voice.rate -and $Rate -eq 0) { $Rate = [int]$script.voice.rate }
$synth.Rate = $Rate
$outDir = Join-Path $app 'audio/voice'
New-Item -ItemType Directory -Force $outDir | Out-Null
$format = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo($SampleRate, [System.Speech.AudioFormat.AudioBitsPerSample]::Sixteen, [System.Speech.AudioFormat.AudioChannel]::Mono)

$script:marks = New-Object System.Collections.ArrayList
$synth.add_SpeakProgress({ param($s, $e) [void]$script:marks.Add(@{ text = $e.Text; pos = $e.CharacterPosition; t = $e.AudioPosition.TotalSeconds }) })

$result = @()
foreach ($p in $script.phrases) {
  $script:marks.Clear()
  $file = Join-Path $outDir ($p.id + '.wav')
  $synth.SetOutputToWaveFile($file, $format)
  $synth.Speak((([string]$p.text) -replace '\s*[|/]\s*', ' ').Trim())
  $synth.SetOutputToNull()
  $bytes = (Get-Item $file).Length - 44
  $duration = [math]::Round($bytes / ($SampleRate * 2), 4)
  $words = @()
  for ($i = 0; $i -lt $script:marks.Count; $i++) {
    $m = $script:marks[$i]
    $end = if ($i + 1 -lt $script:marks.Count) { $script:marks[$i + 1].t } else { $duration }
    $words += [ordered]@{ w = [string]$m.text; start = [math]::Round($m.t, 4); end = [math]::Round($end, 4) }
  }
  $result += [ordered]@{ id = $p.id; file = ('audio/voice/' + $p.id + '.wav'); duration = $duration; timing = 'engine'; words = $words }
  Write-Output ('{0}: {1} s, {2} words' -f $p.id, $duration, $words.Count)
}
$out = [ordered]@{
  comment = 'Generated by scripts/voice-sapi.ps1 from data/voice.json. Times are seconds within each phrase file. Do not edit by hand.'
  engine = ('sapi: ' + $synth.Voice.Name + ', rate ' + $Rate)
  phrases = $result
}
$json = $out | ConvertTo-Json -Depth 6
[System.IO.File]::WriteAllText((Join-Path $app 'data/voice-words.json'), $json, (New-Object System.Text.UTF8Encoding($false)))
Write-Output ('wrote data/voice-words.json with ' + $result.Count + ' phrases')
$synth.Dispose()
